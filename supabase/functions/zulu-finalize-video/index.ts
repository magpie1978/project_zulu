import "jsr:@supabase/functions-js/edge-runtime.d.ts";
import { createClient } from "jsr:@supabase/supabase-js@2";


/* =====================================================================
   ZULU-FINALIZE-VIDEO
   =====================================================================

   PURPOSE
   -------

   Finalises a video after the MP4 itself has successfully uploaded to
   Backblaze B2.

   Responsibilities:

       1. Verify the caller is authenticated.
       2. Optionally restrict access to the configured Zulu administrator.
       3. Validate the supplied video/catalogue metadata.
       4. Validate the associated ingestion record.
       5. Mark the ingestion as "cataloguing".
       6. Protect against duplicate URLs.
       7. Protect against duplicate fingerprints.
       8. Allocate the next catalogue UID.
       9. Insert the zulu_videos record.
      10. Insert actor relationships.
      11. Refresh the search materialized view.
      12. Record the catalogue UID against the ingestion.
      13. Mark the ingestion as "catalogued".
      14. Return the completed catalogue information.

   INGESTION OWNERSHIP
   -------------------

   This function owns the transition:

       video_uploaded
              ↓
         cataloguing
              ↓
          catalogued

   The browser should not mark an ingestion as "catalogued" itself.

   If catalogue creation fails, this function records:

       status       = failed
       failed_stage = cataloguing
       error_message = ...

   This leaves a durable record showing that the MP4 reached Backblaze
   but catalogue finalisation failed.

   ===================================================================== */


/* =====================================================================
   01. CORS
   ===================================================================== */

const corsHeaders = {
  "Access-Control-Allow-Origin":
    "https://pornflix.zulu-orchid-falcon.co.uk",

  "Access-Control-Allow-Headers":
    "authorization, x-client-info, apikey, content-type, x-zulu-automation-key",

  "Access-Control-Allow-Methods":
    "POST, OPTIONS"
};


/* =====================================================================
   02. RESPONSE HELPER
   ===================================================================== */

/**
 * Returns a JSON response with the site's required CORS headers.
 */
function jsonResponse(
  body: unknown,
  status = 200
) {

  return new Response(
    JSON.stringify(body),
    {
      status,

      headers: {
        ...corsHeaders,
        "Content-Type":
          "application/json"
      }
    }
  );
}


/* =====================================================================
   03. REQUEST PAYLOAD
   ===================================================================== */

interface FinalizePayload {

  /*
   * Ingestion journal record created before the video upload begins.
   */
  ingestion_id: string;


  /*
   * Catalogue information.
   */
  film: string;

  url: string;

  actors: string[];

  tags?: string[];


  /*
   * Video metadata generated by add-video.js.
   */
  filesize_bytes?: number;

  duration_seconds?: number;

  width?: number;

  height?: number;

  fingerprint?: string;
}


/* =====================================================================
   04. MAIN EDGE FUNCTION
   ===================================================================== */

Deno.serve(async req => {

  /* -----------------------------------------------------------------
     CORS PREFLIGHT
  ----------------------------------------------------------------- */

  if (
    req.method === "OPTIONS"
  ) {

    return new Response(
      "ok",
      {
        headers:
          corsHeaders
      }
    );
  }


  /*
   * Keep references outside the main try block so the catch handler can
   * record an ingestion failure if catalogue creation throws.
   */
  let supabase:
    ReturnType<typeof createClient> |
    null =
      null;

  let ingestionId:
    string |
    null =
      null;


  try {

    /* ===============================================================
       05. LOAD SERVER CONFIGURATION
       =============================================================== */

    const supabaseUrl =
      Deno.env.get(
        "SUPABASE_URL"
      );


    const supabaseAnonKey =
      Deno.env.get(
        "SUPABASE_ANON_KEY"
      );


    const serviceRoleKey =
      Deno.env.get(
        "SUPABASE_SERVICE_ROLE_KEY"
      );


    const automationKey =
      Deno.env.get(
        "ZULU_AUTOMATION_KEY"
      );


    if (
      !supabaseUrl ||
      !supabaseAnonKey ||
      !serviceRoleKey
    ) {

      return jsonResponse(
        {
          error:
            "Server configuration error"
        },
        500
      );
    }


    /* ===============================================================
       06. DETERMINE AUTHENTICATION METHOD
       ===============================================================

       Two authentication routes are supported:

       1. Existing browser / Add Video route
          Authorization: Bearer <Supabase user access token>

       2. Trusted server automation route
          X-Zulu-Automation-Key: <shared automation secret>

       Supplying an automation header always selects the automation
       route. An invalid automation key is rejected and does not fall
       through to browser authentication.
       =============================================================== */

    const authHeader =
      req.headers.get(
        "Authorization"
      );


    const suppliedAutomationKey =
      req.headers.get(
        "X-Zulu-Automation-Key"
      );


    let authenticatedBy:
      "user" |
      "automation" |
      null =
        null;


    /* ===============================================================
       07. VERIFY AUTOMATION AUTHENTICATION
       =============================================================== */

    if (
      suppliedAutomationKey
    ) {

      if (
        !automationKey
      ) {

        console.error(
          "Automation authentication attempted but ZULU_AUTOMATION_KEY is not configured."
        );


        return jsonResponse(
          {
            error:
              "Automation authentication is not configured"
          },
          500
        );
      }


      if (
        suppliedAutomationKey !==
        automationKey
      ) {

        return jsonResponse(
          {
            error:
              "Unauthorized"
          },
          401
        );
      }


      authenticatedBy =
        "automation";
    }


    /* ===============================================================
       08. VERIFY EXISTING BROWSER USER AUTHENTICATION
       =============================================================== */

    if (
      !authenticatedBy
    ) {

      if (
        !authHeader
          ?.startsWith(
            "Bearer "
          )
      ) {

        return jsonResponse(
          {
            error:
              "Unauthorized"
          },
          401
        );
      }


      const accessToken =
        authHeader.slice(7);


      const authClient =
        createClient(
          supabaseUrl,
          supabaseAnonKey
        );


      const {
        data: {
          user
        },
        error: userError
      } =
        await authClient.auth
          .getUser(
            accessToken
          );


      if (
        userError ||
        !user
      ) {

        return jsonResponse(
          {
            error:
              "Unauthorized"
          },
          401
        );
      }


      const adminEmail =
        Deno.env.get(
          "ZULU_ADMIN_EMAIL"
        );


      if (
        adminEmail &&
        user.email
          ?.toLowerCase() !==
        adminEmail
          .toLowerCase()
      ) {

        return jsonResponse(
          {
            error:
              "Forbidden"
          },
          403
        );
      }


      authenticatedBy =
        "user";
    }


    console.log(
      `zulu-finalize-video authenticated via ${authenticatedBy}.`
    );


    /* ===============================================================
       09. SERVICE-ROLE DATABASE CLIENT
       =============================================================== */

    supabase =
      createClient(
        supabaseUrl,
        serviceRoleKey
      );


    /* ===============================================================
       10. READ REQUEST PAYLOAD
       =============================================================== */

    const {
      ingestion_id,
      film,
      url,
      actors,
      tags = [],

      filesize_bytes,
      duration_seconds,
      width,
      height,
      fingerprint
    }: FinalizePayload =
      await req.json();


    ingestionId =
      ingestion_id;


    /* ===============================================================
       11. BASIC PAYLOAD VALIDATION
       =============================================================== */

    if (
      !ingestionId ||
      !film ||
      !url ||
      !Array.isArray(
        actors
      ) ||
      actors.length === 0
    ) {

      return jsonResponse(
        {
          error:
            "Invalid payload"
        },
        400
      );
    }


    /* ===============================================================
       12. VIDEO METADATA VALIDATION
       =============================================================== */

    if (
      !Number.isFinite(
        filesize_bytes
      ) ||
      filesize_bytes! <= 0 ||

      !Number.isFinite(
        duration_seconds
      ) ||
      duration_seconds! <= 0 ||

      !Number.isInteger(
        width
      ) ||
      width! <= 0 ||

      !Number.isInteger(
        height
      ) ||
      height! <= 0 ||

      !fingerprint ||

      !/^[0-9a-f]{64}$/i
        .test(
          fingerprint
        )
    ) {

      return jsonResponse(
        {
          error:
            "Invalid or incomplete video metadata"
        },
        400
      );
    }


    /* ===============================================================
       13. VALIDATE INGESTION RECORD
       ===============================================================

       The ingestion must already exist before catalogue finalisation.

       This ensures that every catalogue operation can be traced back to
       the persistent ingestion journal.
    =============================================================== */

    const {
      data: ingestion,
      error: ingestionError
    } =
      await supabase
        .schema("zulu").from(
          "zulu_ingestions"
        )
        .select(
          `
            id,
            status,
            video_uid,
            fingerprint,
            public_url
          `
        )
        .eq(
          "id",
          ingestionId
        )
        .maybeSingle();


    if (ingestionError) {
      throw ingestionError;
    }


    if (!ingestion) {

      return jsonResponse(
        {
          error:
            "Ingestion record not found"
        },
        404
      );
    }


    /*
     * A completed ingestion should never be catalogued again.
     */
    if (
      ingestion.status ===
        "complete" ||
      ingestion.status ===
        "complete_without_thumbnail"
    ) {

      return jsonResponse(
        {
          error:
            "Ingestion has already completed",
          uid:
            ingestion.video_uid
        },
        409
      );
    }


    /*
     * If this ingestion already has a video UID, catalogue creation has
     * already happened or partially happened. Do not allocate another UID.
     */
    if (
      ingestion.video_uid != null
    ) {

      return jsonResponse(
        {
          error:
            "Ingestion is already linked to a catalogue video",
          uid:
            ingestion.video_uid
        },
        409
      );
    }


    /* ===============================================================
       14. MARK INGESTION AS CATALOGUING
       =============================================================== */

    const {
      error:
        cataloguingStatusError
    } =
      await supabase
        .schema("zulu").from(
          "zulu_ingestions"
        )
        .update({
          status:
            "cataloguing",

          failed_stage:
            null,

          error_message:
            null,

          updated_at:
            new Date()
              .toISOString()
        })
        .eq(
          "id",
          ingestionId
        );


    if (
      cataloguingStatusError
    ) {
      throw cataloguingStatusError;
    }


    /* ===============================================================
       15. PREVENT DUPLICATE URL
       =============================================================== */

    const {
      data: existingUrl,
      error: existingUrlError
    } =
      await supabase
        .schema("zulu").from(
          "zulu_videos"
        )
        .select(
          "uid, film"
        )
        .eq(
          "url",
          url
        )
        .maybeSingle();


    if (existingUrlError) {
      throw existingUrlError;
    }


    if (existingUrl) {

      await supabase
        .schema("zulu").from(
          "zulu_ingestions"
        )
        .update({
          status:
            "duplicate",

          failed_stage:
            "cataloguing",

          error_message:
            "A video with this URL already exists",

          video_uid:
            existingUrl.uid,

          updated_at:
            new Date()
              .toISOString()
        })
        .eq(
          "id",
          ingestionId
        );


      return jsonResponse(
        {
          error:
            "A video with this URL already exists",

          duplicate:
            true,

          uid:
            existingUrl.uid,

          film:
            existingUrl.film
        },
        409
      );
    }


    /* ===============================================================
       16. PREVENT DUPLICATE FINGERPRINT
       ===============================================================

       This duplicates the browser-side check intentionally.

       The server must still protect against:

           - simultaneous submissions;
           - stale browser state;
           - bypassing the browser-side check.
    =============================================================== */

    const {
      data:
        existingFingerprint,

      error:
        existingFingerprintError
    } =
      await supabase
        .schema("zulu").from(
          "zulu_videos"
        )
        .select(
          "uid, film, url"
        )
        .eq(
          "fingerprint",
          fingerprint
        )
        .maybeSingle();


    if (
      existingFingerprintError
    ) {
      throw existingFingerprintError;
    }


    if (
      existingFingerprint
    ) {

      await supabase
        .schema("zulu").from(
          "zulu_ingestions"
        )
        .update({
          status:
            "duplicate",

          failed_stage:
            "cataloguing",

          error_message:
            "This video appears to already exist",

          video_uid:
            existingFingerprint.uid,

          updated_at:
            new Date()
              .toISOString()
        })
        .eq(
          "id",
          ingestionId
        );


      return jsonResponse(
        {
          error:
            "This video appears to already exist",

          duplicate:
            true,

          uid:
            existingFingerprint.uid,

          film:
            existingFingerprint.film,

          url:
            existingFingerprint.url
        },
        409
      );
    }


    /* ===============================================================
       17. DETERMINE NEXT UID
       =============================================================== */

    const {
      data:
        maxUidRow,

      error:
        maxUidError
    } =
      await supabase
        .schema("zulu").from(
          "zulu_videos"
        )
        .select(
          "uid"
        )
        .order(
          "uid",
          {
            ascending:
              false
          }
        )
        .limit(1)
        .maybeSingle();


    if (maxUidError) {
      throw maxUidError;
    }


    const uid =
      (
        maxUidRow
          ?.uid ??
        0
      ) + 1;


    /* ===============================================================
       18. PREPARE TAGS
       =============================================================== */

    const tagsValue =
      Array.isArray(
        tags
      )
        ? tags.join(
            ", "
          )
        : "";


    /* ===============================================================
       19. INSERT ZULU_VIDEOS ROW
       =============================================================== */

    const {
      error: videoError
    } =
      await supabase
        .schema("zulu").from(
          "zulu_videos"
        )
        .insert({
          uid,

          film,

          url,

          tags:
            tagsValue,

          filesize_bytes,

          duration_seconds,

          width,

          height,

          fingerprint:
            fingerprint
              .toLowerCase()
        });


    if (videoError) {
      throw videoError;
    }


    /* ===============================================================
       20. CLEAN ACTOR LIST
       =============================================================== */

    const cleanActors =
      [
        ...new Set(
          actors
            .map(
              actor =>
                actor.trim()
            )
            .filter(
              Boolean
            )
        )
      ];


    /*
     * This should normally already be guaranteed by the initial payload
     * validation, but cleaning can theoretically turn whitespace-only
     * actor values into an empty array.
     */
    if (
      cleanActors.length === 0
    ) {

      await supabase
        .schema("zulu").from(
          "zulu_videos"
        )
        .delete()
        .eq(
          "uid",
          uid
        );


      throw new Error(
        "No valid actors remained after normalization."
      );
    }


    /* ===============================================================
       21. INSERT ACTOR RELATIONSHIPS
       =============================================================== */

    const actorRows =
      cleanActors.map(
        actor => ({
          uid,
          actor
        })
      );


    const {
      error: actorsError
    } =
      await supabase
        .schema("zulu").from(
          "zulu_actors"
        )
        .insert(
          actorRows
        );


    if (actorsError) {

      /*
       * Roll back the video record if actor creation fails.
       *
       * This preserves the behaviour of the existing function.
       */
      await supabase
        .schema("zulu").from(
          "zulu_videos"
        )
        .delete()
        .eq(
          "uid",
          uid
        );


      throw actorsError;
    }


    /* ===============================================================
       22. REFRESH SEARCH MATERIALIZED VIEW
       =============================================================== */

    const {
      error: refreshError
    } =
      await supabase.rpc(
        "refresh_zulu_videos_search"
      );


    if (refreshError) {

      console.error(
        "Materialized view refresh failed:",
        refreshError
      );


      /*
       * Unlike actor insertion failure, do NOT delete the catalogue
       * records here.

       * The video and actors now genuinely exist in the catalogue.

       * The ingestion manager must therefore preserve that fact rather
       * than pretending the entire catalogue operation was rolled back.
       */

      const {
        error:
          ingestionUpdateError
      } =
        await supabase
          .schema("zulu").from(
            "zulu_ingestions"
          )
          .update({
            status:
              "catalogued",

            video_uid:
              uid,

            catalogued_at:
              new Date()
                .toISOString(),

            failed_stage:
              null,

            error_message:
              "Catalogue saved, but search refresh failed",

            updated_at:
              new Date()
                .toISOString()
          })
          .eq(
            "id",
            ingestionId
          );


      if (
        ingestionUpdateError
      ) {

        console.error(
          "Could not update ingestion after search refresh failure:",
          ingestionUpdateError
        );
      }


      return jsonResponse(
        {
          error:
            "Video saved, but search refresh failed",

          catalogue_saved:
            true,

          search_refresh_failed:
            true,

          uid
        },
        500
      );
    }


    /* ===============================================================
       23. MARK INGESTION AS CATALOGUED
       ===============================================================

       Catalogue creation is now complete.

       Thumbnail processing is deliberately NOT performed here. That is
       the next stage of the browser ingestion workflow.
    =============================================================== */

    const cataloguedAt =
      new Date()
        .toISOString();


    const {
      error:
        ingestionUpdateError
    } =
      await supabase
        .schema("zulu").from(
          "zulu_ingestions"
        )
        .update({
          status:
            "catalogued",

          video_uid:
            uid,

          catalogued_at:
            cataloguedAt,

          failed_stage:
            null,

          error_message:
            null,

          updated_at:
            cataloguedAt
        })
        .eq(
          "id",
          ingestionId
        );


    if (
      ingestionUpdateError
    ) {

      /*
       * The catalogue itself has been created successfully.

       * Do NOT roll it back merely because updating the ingestion journal
       * failed. Log this separately so the catalogue remains intact.
       */
      console.error(
        "Catalogue created but ingestion status update failed:",
        ingestionUpdateError
      );


      return jsonResponse(
        {
          error:
            "Video catalogued, but ingestion status could not be updated",

          catalogue_saved:
            true,

          ingestion_update_failed:
            true,

          uid
        },
        500
      );
    }


    /* ===============================================================
       24. SUCCESS
       =============================================================== */

    return jsonResponse({
      success:
        true,

      ingestion_id:
        ingestionId,

      ingestion_status:
        "catalogued",

      uid,

      film,

      actors:
        cleanActors,

      url,

      metadata: {

        filesize_bytes,

        duration_seconds,

        width,

        height,

        fingerprint:
          fingerprint
            .toLowerCase()
      }
    });


  } catch (error) {

    /* ===============================================================
       25. UNEXPECTED CATALOGUE FAILURE
       =============================================================== */

    console.error(
      "zulu-finalize-video error:",
      error
    );


    /*
     * If we know which ingestion was being processed and have already
     * established the service-role client, record the failure.

     * This update is deliberately best-effort. Failure to update the
     * journal must not conceal the original catalogue error.
     */
    if (
      supabase &&
      ingestionId
    ) {

      try {

        const {
          error:
            failureUpdateError
        } =
          await supabase
            .schema("zulu").from(
              "zulu_ingestions"
            )
            .update({
              status:
                "failed",

              failed_stage:
                "cataloguing",

              error_message:
                error instanceof Error
                  ? error.message
                  : "Unknown catalogue finalization error",

              updated_at:
                new Date()
                  .toISOString()
            })
            .eq(
              "id",
              ingestionId
            );


        if (
          failureUpdateError
        ) {

          console.error(
            "Could not record ingestion failure:",
            failureUpdateError
          );
        }

      } catch (
        ingestionFailureError
      ) {

        console.error(
          "Unexpected error while recording ingestion failure:",
          ingestionFailureError
        );
      }
    }


    return jsonResponse(
      {
        error:
          "Could not finalize video catalogue entry"
      },
      500
    );
  }
});